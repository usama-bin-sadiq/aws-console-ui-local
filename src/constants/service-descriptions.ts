/** Category for a service href, falling back to `Other`. */
export function getServiceCategory(href: string): string {
  return SERVICE_CATEGORY_MAP[href] || "Other";
}

/** Short AWS-style service description, or an empty string when unknown. */
export function getServiceDescription(text: string | undefined): string {
  return (text && SERVICE_DESCRIPTIONS[text]) || "";
}

